// Smoke test of the demo build: every screen for every demo account, no JS errors, no network, role scoping.
import { createRequire } from "node:module";
import { readFileSync } from "node:fs";
const req = createRequire(import.meta.url);
let pw; try { pw = req("playwright"); } catch { pw = req("/opt/npm-tools/node_modules/playwright"); }
const HTML = readFileSync(new URL("../../dist/yaqen-demo.html", import.meta.url), "utf8");
const URL_ = "https://demo.local/";
const b = await pw.chromium.launch({ executablePath:"/usr/bin/google-chrome", args:["--no-sandbox"] });
const ctx = await b.newContext({ locale:"ar-SA", viewport:{ width:1280, height:900 } });
const page = await ctx.newPage(); page.setDefaultTimeout(5000);
const errors = [], net = [];
page.on("pageerror", (e) => errors.push(e.message));
page.on("dialog", (d) => d.accept());
await ctx.route("**/*", (r) => { const u = r.request().url(); if (u === URL_) return r.fulfill({ contentType:"text/html; charset=utf-8", body:HTML }); if (!u.startsWith("data:") && !u.startsWith("blob:")) net.push(u); return r.abort(); });
let res = [];
const ok = (n, p, d = "") => { res.push(p); console.log((p ? "PASS" : "FAIL") + " | " + n + (d ? " | " + d : "")); };
const go = async (v) => { await page.evaluate((v) => window.App.go(v), v); await page.waitForTimeout(250); };
await page.goto(URL_); await page.waitForTimeout(400);
ok("demo opens on the login screen with the demo bar", await page.locator("#demoBar").isVisible() && (await page.textContent("#app")).includes("تسجيل الدخول"));
await page.click("#demoBar >> text=مدير الشركة"); await page.waitForTimeout(600);
ok("admin sees the dashboard", await page.locator(".shell").count() === 1);
await page.screenshot({ path:"dist/demo_admin_home.png" });
await page.click("#briefBtn"); await page.waitForTimeout(300);
ok("brief is clearly labelled as illustrative", (await page.textContent("#content")).includes("تقرير توضيحي"));
for (const v of ["ai","rooms","notes","departments","people","vehicles","projects","legal_cases","invoices","documents","requests","audit","trash","whatsapp","settings","profile"]) await go(v);
await go("invoices");
ok("invoices paged (50 of 148)", (await page.locator(".rec").count()) === 50 && (await page.textContent("#content")).includes("صفحة 1 من 3"));
await go("people");
ok("pending approvals shown (2)", (await page.textContent("#content")).includes("بانتظار موافقتك (2)"));
await page.selectOption('form[onsubmit*="approve"] select[name="dept"] >> nth=0', { index:2 }); await page.click('form[onsubmit*="approve"] button.pri >> nth=0'); await page.waitForTimeout(400);
ok("approving a member works", (await page.textContent("#content")).includes("بانتظار موافقتك (1)"));
await go("vehicles"); await page.locator(".rec").first().click(); await page.waitForTimeout(300); await page.click("form#ef button.danger"); await page.waitForTimeout(400);
await go("trash"); await page.waitForTimeout(300);
ok("soft delete lands in trash (2 items)", (await page.locator("#content tr").count()) === 2);
await go("audit"); await page.waitForTimeout(300);
ok("audit log records the actions", (await page.locator("#auditBox tr").count()) >= 2);
await go("rooms"); await page.locator(".rec, .card").filter({ hasText:"أبقيق" }).first().click(); await page.waitForTimeout(400);
ok("room shows the Urdu message with its stored translation", (await page.textContent("#content")).includes("إطار السيارة"));
await page.fill("#rmInput", "رسالة تجربة من العرض"); await page.press("#rmInput", "Enter"); await page.waitForTimeout(300);
ok("sending a room message works", (await page.textContent("#content")).includes("رسالة تجربة من العرض"));
await page.click("#demoBar >> text=موظف الأسطول"); await page.waitForTimeout(700);
await go("invoices");
ok("fleet employee sees no invoices (department scoping)", (await page.locator(".rec").count()) === 0);
await go("vehicles");
ok("fleet employee sees fleet vehicles", (await page.locator(".rec").count()) > 0);
  ok("signed in as the fleet employee", (await page.textContent(".top .me")).includes("خالد المطيري"));
await page.screenshot({ path:"dist/demo_employee.png" });
await page.click("#demoBar >> text=مسؤول المنصة"); await page.waitForTimeout(700);
ok("platform owner sees 3 demo companies", (await page.textContent("#content")).includes("مؤسسة الواحة"));
await page.evaluate(() => window.App.logout()); await page.waitForTimeout(500);
await page.click("text=حساب جديد"); await page.fill("#coCode", "DEMOJOIN2026"); await page.click("text=تحقق"); await page.waitForTimeout(300);
await page.fill('input[name="full_name"]', "زائر العرض"); await page.fill('input[name="email"]', "visitor@demo.test"); await page.fill('input[name="password"]', "12345678");
await page.click("text=إنشاء الحساب"); await page.waitForTimeout(400);
ok("sign-up with the demo code creates a pending account", (await page.textContent("#app")).includes("تم إنشاء الحساب"));
ok("no JS errors", errors.length === 0, errors.slice(0, 3).join(" / "));
ok("no network requests except Google Fonts", net.every((u) => u.includes("fonts.g")), net.filter((u) => !u.includes("fonts.g")).slice(0, 3).join(" "));
await b.close();
console.log(`---- ${res.filter(Boolean).length} passed, ${res.filter((x) => !x).length} failed of ${res.length}`);
process.exit(res.every(Boolean) ? 0 : 1);
